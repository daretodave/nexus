#!/usr/bin/env node
// scripts/upgrade-files.mjs: the v2 kit file set, computed (spec 58).
//
// One list feeds every way a repo gets the v2 kit: the CLI's bundled
// copy (packages/cli/scripts/bundle-kit.mjs writes it to
// kit/upgrade/) and the manual appendix of playbooks/upgrade.md
// (generated between its upgrade-files markers). The list is:
//
//   - the import closures (static and dynamic relative imports, and
//     `new URL('./x', import.meta.url)` loads) of plan-check,
//     upgrade-plan, claims, cloud/tick, workflow-lint (the upgrade's
//     gate runs it), and every script a listed skill or command, or
//     the march.yml the upgrade merges, calls (next and plot among
//     them, scanned from their text; a name the kit does not ship is
//     an example);
//   - the fixed non-script files: every skill, every command, the
//     shared toolchain action, and plan-check's own test;
//   - twins: the kit's own test of a listed script, as `twin`. It
//     replaces an older copy a repo carries (that copy fails the new
//     script) and is never added where the repo has none.
//
// Every path is a kit path (templates/...) with the place it goes in
// a repo (templates/claude/ lands in .claude/). Lanes files are listed
// as `lane`: seeded when missing, never overwritten.
//
//   node scripts/upgrade-files.mjs           # the list, one per line
//   node scripts/upgrade-files.mjs --json    # the list as JSON
//   node scripts/upgrade-files.mjs --write   # regenerate the appendix
//   node scripts/upgrade-files.mjs --check   # the verify gate's upgrade leg
//
// --check fails when a templates/ path the playbook names does not
// exist, when the appendix drifts from the list, or when a listed
// script reaches (by import) a file the list lacks or that is gone.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

/** Script entries whose closures are always in the set (relative to templates/scripts). */
export const ENTRIES = Object.freeze(['plan-check.mjs', 'upgrade-plan.mjs', 'claims.mjs', 'cloud/tick.mjs', 'workflow-lint.mjs'])
/** Workflows the upgrade merges into a repo (never copies): the scripts they call ship, or the first tick fails. */
export const WORKFLOWS = Object.freeze(['.github/workflows/march.yml'])
/** Fixed non-script files: whole directories (recursive) and single files, relative to templates/. */
export const FIXED_DIRS = Object.freeze(['skills', 'claude/commands', '.github/actions/setup'])
export const FIXED_FILES = Object.freeze(['scripts/__tests__/plan-check.test.mjs'])
/** The project-lanes files: the kit seeds them, never overwrites them (customization/project-lanes.md). */
export const LANE_FILES = Object.freeze(['skills/march.lanes.md', 'skills/iterate.lanes.md'])
export const PLAYBOOK = 'playbooks/upgrade.md'
export const BEGIN = '<!-- upgrade-files:begin (generated by node scripts/upgrade-files.mjs --write; do not edit by hand) -->'
export const END = '<!-- upgrade-files:end -->'

const SCRIPT = /\.(mjs|js)$/
const IMPORT = /(?:\bfrom|\bimport\s*\(?|\bnew\s+URL\s*\()\s*['"](\.{1,2}\/[^'"]+)['"]/g
const CALL = /(?<![\w./-])scripts\/([\w./-]+?\.(?:mjs|js))\b/g

const posix = (p) => p.split(path.sep).join('/')

/** The relative import specifiers in a script's text, comments left out (a commented import is not a dependency). */
export function importsOf(text) {
  const code = text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '')
  return [...code.matchAll(IMPORT)].map((m) => m[1])
}

/** The `scripts/<x>` files a skill's text calls, relative to the scripts dir. */
export function callsOf(text) {
  return [...new Set([...text.matchAll(CALL)].map((m) => m[1]))]
}

/**
 * The closure of `entries` under `scriptsDir`: every file reached by a relative import, walked. Returns
 * { files, missing }: files reached (relative, posix, sorted) and imports whose target is not on disk
 * (`<importer> -> <target>`).
 */
export function closure(scriptsDir, entries) {
  const seen = new Set()
  const missing = []
  const queue = entries.map((e) => ({ f: e, from: null }))
  while (queue.length) {
    const { f, from } = queue.shift()
    if (seen.has(f)) continue
    const abs = path.join(scriptsDir, ...f.split('/'))
    if (!fs.existsSync(abs)) {
      missing.push(from ? `${from} -> ${f}` : f)
      continue
    }
    if (fs.statSync(abs).isDirectory()) continue // a URL to a folder (a fixture root), not a module
    seen.add(f)
    if (!SCRIPT.test(f)) continue
    for (const spec of importsOf(fs.readFileSync(abs, 'utf8'))) {
      queue.push({ f: path.posix.normalize(path.posix.join(path.posix.dirname(f), spec)), from: f })
    }
  }
  return { files: [...seen].sort(), missing }
}

function walk(dirAbs) {
  if (!fs.existsSync(dirAbs)) return []
  const out = []
  for (const e of fs.readdirSync(dirAbs, { withFileTypes: true })) {
    const abs = path.join(dirAbs, e.name)
    if (e.isDirectory()) out.push(...walk(abs))
    else out.push(abs)
  }
  return out
}

/** Where a kit path lands in a repo: templates/claude/... -> .claude/..., else templates/ stripped. */
export function repoPath(kit) {
  const rel = kit.replace(/^templates\//, '')
  return rel.startsWith('claude/') ? `.${rel}` : rel
}

/** The fixed non-script files, as kit paths (templates/...), sorted. */
export function fixedFiles(root = ROOT) {
  const t = path.join(root, 'templates')
  const out = new Set()
  for (const d of FIXED_DIRS) for (const abs of walk(path.join(t, ...d.split('/')))) out.add(posix(path.relative(root, abs)))
  for (const f of FIXED_FILES) if (fs.existsSync(path.join(t, ...f.split('/')))) out.add(`templates/${f}`)
  return [...out].sort()
}

/** The script entries: the fixed ones plus every shipped script a listed skill or command, or a merged workflow, calls. */
export function entries(root = ROOT) {
  const t = path.join(root, 'templates')
  const out = [...ENTRIES]
  const sources = [...fixedFiles(root).filter((k) => k.endsWith('.md')), ...WORKFLOWS.map((w) => `templates/${w}`)]
  for (const kit of sources) {
    const abs = path.join(root, ...kit.split('/'))
    if (!fs.existsSync(abs)) continue
    for (const s of callsOf(fs.readFileSync(abs, 'utf8'))) {
      if (!out.includes(s) && fs.existsSync(path.join(t, 'scripts', ...s.split('/')))) out.push(s)
    }
  }
  return out
}

/**
 * The v2 kit file set: [{ kit, repo, kind }], sorted by kit path. kind: script | test | twin | skill | lane | command
 * | action. Also returns `missing` (imports that reach no file) for the gate.
 */
export function upgradeFiles(root = ROOT) {
  const t = path.join(root, 'templates')
  const scriptsDir = path.join(t, 'scripts')
  const fixedScripts = FIXED_FILES.filter((f) => f.startsWith('scripts/')).map((f) => f.slice('scripts/'.length))
  const { files: scripts, missing } = closure(scriptsDir, [...entries(root), ...fixedScripts])
  const kits = new Set([...scripts.map((f) => `templates/scripts/${f}`), ...fixedFiles(root)])
  const kindOf = (k) => {
    const rel = k.replace(/^templates\//, '')
    if (LANE_FILES.includes(rel)) return 'lane'
    if (rel.startsWith('scripts/__tests__/')) return 'test'
    if (rel.startsWith('scripts/')) return 'script'
    if (rel.startsWith('skills/')) return 'skill'
    if (rel.startsWith('claude/commands/')) return 'command'
    return 'action'
  }
  const files = [...kits].sort().map((kit) => ({ kit, repo: repoPath(kit), kind: kindOf(kit) }))
  // Twins: the kit's own test of a listed script. A v1 repo often carries an older copy of it, which the new script
  // fails (an enum grew), so the twin replaces that copy; a repo without one gets none. Only a twin whose every
  // import is listed (no fixture folder, no unlisted module) ships.
  for (const f of twinTests(scriptsDir, scripts)) {
    const kit = `templates/scripts/${f}`
    if (!kits.has(kit)) files.push({ kit, repo: repoPath(kit), kind: 'twin' })
  }
  files.sort((a, b) => (a.kit < b.kit ? -1 : a.kit > b.kit ? 1 : 0))
  return { files, missing }
}

/** The kit tests (`__tests__/<name>.test.mjs`) of the listed scripts whose relative imports are all listed. */
export function twinTests(scriptsDir, scripts) {
  const listed = new Set(scripts)
  const out = []
  for (const s of scripts) {
    if (!/^[\w.-]+\.mjs$/.test(s)) continue
    const t = `__tests__/${s.replace(/\.mjs$/, '.test.mjs')}`
    const abs = path.join(scriptsDir, ...t.split('/'))
    if (listed.has(t) || !fs.existsSync(abs)) continue
    const deps = importsOf(fs.readFileSync(abs, 'utf8')).map((spec) => path.posix.normalize(path.posix.join('__tests__', spec)))
    if (deps.every((d) => listed.has(d))) out.push(t)
  }
  return out.sort()
}

const winPath = (p) => p.split('/').join('\\')

/** The playbook's manual appendix for a list: per destination folder, a table row and the copy commands. */
export function appendix(files) {
  const copy = files.filter((f) => f.kind !== 'lane' && f.kind !== 'twin')
  const lanes = files.filter((f) => f.kind === 'lane')
  const twins = files.filter((f) => f.kind === 'twin')
  const groups = new Map()
  for (const f of copy) {
    const to = path.posix.dirname(f.repo)
    if (!groups.has(to)) groups.set(to, [])
    groups.get(to).push(f)
  }
  const dirs = [...groups.keys()].sort()
  const lines = [BEGIN, '']
  lines.push(`${copy.length} files in ${dirs.length} folders, plus ${lanes.length} lanes files.`, '')
  lines.push('| Folder in your repo | Files (from `nexus/templates/`) |', '|---|---|')
  for (const d of dirs) lines.push(`| \`${d}/\` | ${groups.get(d).map((f) => `\`${path.posix.basename(f.repo)}\``).join(', ')} |`)
  lines.push('', 'The copy, from your repo root with nexus at `../nexus`:', '', '```bash')
  for (const d of dirs) {
    lines.push(`mkdir -p ${d}`)
    const fs_ = groups.get(d)
    lines.push(`cp ${fs_.map((f) => `../nexus/${f.kit}`).join(' \\\n   ')} \\\n   ${d}/`)
  }
  lines.push('```', '', 'The PowerShell twin:', '', '```powershell')
  for (const d of dirs) {
    lines.push(`New-Item -ItemType Directory -Force ${winPath(d)} | Out-Null`)
    const fs_ = groups.get(d)
    lines.push(`Copy-Item -Destination ${winPath(d)} -Path ${fs_.map((f) => `..\\nexus\\${winPath(f.kit)}`).join(',\n  ')}`)
  }
  lines.push('```', '')
  if (lanes.length) {
    lines.push(`The lanes files (${lanes.map((f) => `\`${f.repo}\``).join(', ')}) are copied only when your repo has none: they hold your own steps, and nothing overwrites them.`, '')
  }
  if (twins.length) {
    lines.push(`The kit's tests of the scripts above go only over a copy your repo already has (an older copy fails the new script): ${twins.map((f) => `\`${f.repo}\``).join(', ')}.`, '')
  }
  lines.push(END)
  return lines.join('\n')
}

/** The appendix block in a playbook's text, markers included; null when the markers are absent. */
export function appendixIn(text) {
  const t = text.replace(/\r\n/g, '\n')
  const a = t.indexOf(BEGIN)
  const b = t.indexOf(END)
  if (a < 0 || b < a) return null
  return t.slice(a, b + END.length)
}

/** Every templates/ path a playbook names (backticked or bare, with or without the ../nexus/ prefix). */
export function namedPaths(text) {
  const out = new Set()
  for (const m of text.matchAll(/(?<![\w-])templates[/\\]([\w.\-/\\]*[\w-])/g)) {
    const p = `templates/${m[1].replace(/\\/g, '/')}`
    if (/[<>*]/.test(p)) continue
    out.add(p)
  }
  return [...out].sort()
}

/** The upgrade leg: { problems, files }. */
export function check(root = ROOT) {
  const problems = []
  const { files, missing } = upgradeFiles(root)
  for (const m of missing) problems.push(`templates/scripts: a listed script imports a file that does not exist (${m})`)
  // The closure is closed: every relative import of every listed script is itself listed.
  const listed = new Set(files.map((f) => f.kit))
  for (const f of files) {
    if (!SCRIPT.test(f.kit)) continue
    const abs = path.join(root, ...f.kit.split('/'))
    for (const spec of importsOf(fs.readFileSync(abs, 'utf8'))) {
      const target = path.posix.normalize(path.posix.join(path.posix.dirname(f.kit), spec))
      const tabs = path.join(root, ...target.split('/'))
      if (!listed.has(target) && fs.existsSync(tabs) && fs.statSync(tabs).isFile()) problems.push(`${f.kit} imports ${target}, which the upgrade list lacks`)
    }
  }
  const pb = path.join(root, ...PLAYBOOK.split('/'))
  if (!fs.existsSync(pb)) return { problems: [...problems, `${PLAYBOOK}: missing`], files }
  const text = fs.readFileSync(pb, 'utf8')
  for (const p of namedPaths(text)) {
    if (!fs.existsSync(path.join(root, ...p.split('/')))) problems.push(`${PLAYBOOK} names ${p}, which does not exist`)
  }
  const block = appendixIn(text)
  if (block === null) problems.push(`${PLAYBOOK}: no generated appendix (the upgrade-files markers); run node scripts/upgrade-files.mjs --write`)
  else if (block !== appendix(files)) {
    const have = new Set([...block.matchAll(/\.\.\/nexus\/(templates\/\S+?)(?= |$)/gm)].map((m) => m[1]))
    const lacks = files.filter((f) => f.kind !== 'lane' && f.kind !== 'twin' && !have.has(f.kit)).map((f) => f.kit)
    problems.push(`${PLAYBOOK}: the manual appendix is stale${lacks.length ? ` (lacks ${lacks.join(', ')})` : ''}; run node scripts/upgrade-files.mjs --write`)
  }
  return { problems, files }
}

/** Rewrites the playbook's appendix from the list; returns true when the file changed. */
export function writeAppendix(root = ROOT) {
  const pb = path.join(root, ...PLAYBOOK.split('/'))
  const text = fs.readFileSync(pb, 'utf8').replace(/\r\n/g, '\n')
  const block = appendixIn(text)
  if (block === null) throw new Error(`${PLAYBOOK}: add the markers first:\n${BEGIN}\n${END}`)
  const next = text.replace(block, () => appendix(upgradeFiles(root).files))
  if (next === text) return false
  fs.writeFileSync(pb, next)
  return true
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const arg = process.argv[2]
  if (arg === '--check') {
    const { problems, files } = check()
    for (const p of problems) console.error(`upgrade-files: ${p}`)
    if (!problems.length) console.log(`upgrade-files: ${files.length} files; the closure is closed and ${PLAYBOOK} matches`)
    process.exit(problems.length ? 1 : 0)
  } else if (arg === '--write') {
    console.log(writeAppendix() ? `upgrade-files: rewrote the appendix in ${PLAYBOOK}` : `upgrade-files: ${PLAYBOOK} already current`)
  } else if (arg === '--json') {
    console.log(JSON.stringify(upgradeFiles().files, null, 2))
  } else {
    for (const f of upgradeFiles().files) console.log(`${f.kind.padEnd(8)} ${f.kit} -> ${f.repo}`)
  }
}
